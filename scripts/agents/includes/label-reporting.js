/**
 * Build a comprehensive Markdown summary for labeling actions
 * @param {Object} data - Labeling action data
 * @param {string[]} [data.added=[]] - Labels that were added
 * @param {string[]} [data.removed=[]] - Labels that were removed
 * @param {Array<{from: string, to: string}>} [data.migrated=[]] - Labels that were migrated
 * @param {Object} [data.context] - GitHub context object
 * @param {string[]} [data.rulesApplied=[]] - Rules that matched
 * @param {string[]} [data.errors=[]] - Errors encountered
 * @returns {string} Markdown formatted report
 */
function buildLabelingReport(data = {}) {
  const added = data.added || [];
  const removed = data.removed || [];
  const migrated = data.migrated || [];
  const rulesApplied = data.rulesApplied || [];
  const errors = data.errors || [];
  const context = data.context;

  let report = "## 🏷️ Label Actions Report\n\n";

  // Add summary statistics
  const totalChanges = added.length + removed.length + migrated.length;
  report += `**Total Changes:** ${totalChanges}\n\n`;

  // Context information
  if (context) {
    const isPR = !!context.payload.pull_request;
    const number = isPR
      ? context.payload.pull_request.number
      : context.payload.issue?.number;
    const type = isPR ? "Pull Request" : "Issue";
    report += `**${type}:** #${number}\n\n`;
  }

  // Added labels
  if (added.length > 0) {
    report += `### ➕ Added Labels (${added.length})\n\n`;
    added.forEach((label) => {
      report += `- \`${label}\`\n`;
    });
    report += "\n";
  }

  // Removed labels
  if (removed.length > 0) {
    report += `### ➖ Removed Labels (${removed.length})\n\n`;
    removed.forEach((label) => {
      report += `- \`${label}\`\n`;
    });
    report += "\n";
  }

  // Migrated labels
  if (migrated.length > 0) {
    report += `### 🔄 Migrated Labels (${migrated.length})\n\n`;
    migrated.forEach((m) => {
      report += `- \`${m.from}\` → \`${m.to}\`\n`;
    });
    report += "\n";
  }

  // Rules applied
  if (rulesApplied.length > 0) {
    report += `### 📋 Rules Applied\n\n`;
    rulesApplied.forEach((rule) => {
      report += `- ${rule}\n`;
    });
    report += "\n";
  }

  // Errors
  if (errors.length > 0) {
    report += `### ⚠️ Errors (${errors.length})\n\n`;
    errors.forEach((error) => {
      report += `- ${error}\n`;
    });
    report += "\n";
  }

  // No changes message
  if (totalChanges === 0 && errors.length === 0) {
    report += "_No label changes required._\n\n";
  }

  report += "_Generated by LightSpeedWP Labeling Agent_";
  return report;
}

/**
 * Build a comprehensive markdown report for label standardization actions
 * @param {Object} data - Standardization data
 * @param {string[]} [data.nonStandardLabels=[]] - Non-standard labels found
 * @param {Array<{from: string, to: string, item: string}>} [data.migratedLabels=[]] - Labels that were migrated
 * @param {number} [data.itemsProcessed=0] - Number of items processed
 * @param {string[]} [data.errors=[]] - Errors encountered
 * @returns {string} Markdown formatted report
 */
function buildStandardizationReport(data = {}) {
  const nonStandardLabels = data.nonStandardLabels || [];
  const migratedLabels = data.migratedLabels || [];
  const itemsProcessed = data.itemsProcessed || 0;
  const errors = data.errors || [];

  let report = `## 🏷️ Label Standardization Report\n\n`;

  // Summary statistics
  report += `**Statistics:**\n`;
  report += `- Items processed: ${itemsProcessed}\n`;
  report += `- Non-standard labels found: ${nonStandardLabels.length}\n`;
  report += `- Labels migrated: ${migratedLabels.length}\n`;
  report += `- Errors: ${errors.length}\n\n`;

  // Non-standard labels
  if (nonStandardLabels.length > 0) {
    report += `### Non-standard Labels Detected\n\n`;
    nonStandardLabels.forEach((label) => {
      report += `- \`${label}\`\n`;
    });
    report += "\n";
  } else {
    report += `### ✅ No non-standard labels found\n\n`;
  }

  // Migrated labels
  if (migratedLabels.length > 0) {
    report += `### Migrated Labels\n\n`;
    migratedLabels.forEach((m) => {
      const item = m.item ? ` (${m.item})` : "";
      report += `- \`${m.from}\` → \`${m.to}\`${item}\n`;
    });
    report += "\n";
  }

  // Errors
  if (errors.length > 0) {
    report += `### ⚠️ Errors\n\n`;
    errors.forEach((error) => {
      report += `- ${error}\n`;
    });
    report += "\n";
  }

  report += `\n_Repository labels now conform to org-wide standards._\n`;
  report += `_Generated by LightSpeedWP Labeling Agent_`;
  return report;
}

/**
 * Build a dry-run preview report
 * @param {Object} data - Dry run data
 * @param {string[]} [data.labelsToAdd=[]] - Labels that would be added
 * @param {string[]} [data.labelsToRemove=[]] - Labels that would be removed
 * @param {Array<{from: string, to: string}>} [data.labelsMigrate=[]] - Labels that would be migrated
 * @returns {string} Markdown formatted dry-run report
 */
function buildDryRunReport(data = {}) {
  const labelsToAdd = data.labelsToAdd || [];
  const labelsToRemove = data.labelsToRemove || [];
  const labelsMigrate = data.labelsMigrate || [];

  let report = `## 🔍 Dry Run Report - Preview of Changes\n\n`;
  report += `_This is a preview only. No changes will be applied._\n\n`;

  const totalChanges =
    labelsToAdd.length + labelsToRemove.length + labelsMigrate.length;
  report += `**Total Proposed Changes:** ${totalChanges}\n\n`;

  if (labelsToAdd.length > 0) {
    report += `### Would Add (${labelsToAdd.length})\n\n`;
    labelsToAdd.forEach((label) => {
      report += `- \`${label}\`\n`;
    });
    report += "\n";
  }

  if (labelsToRemove.length > 0) {
    report += `### Would Remove (${labelsToRemove.length})\n\n`;
    labelsToRemove.forEach((label) => {
      report += `- \`${label}\`\n`;
    });
    report += "\n";
  }

  if (labelsMigrate.length > 0) {
    report += `### Would Migrate (${labelsMigrate.length})\n\n`;
    labelsMigrate.forEach((m) => {
      report += `- \`${m.from}\` → \`${m.to}\`\n`;
    });
    report += "\n";
  }

  if (totalChanges === 0) {
    report += `_No changes would be made._\n\n`;
  }

  report += `\n_To apply these changes, run without dry-run mode._`;
  return report;
}

/**
 * Format errors for reporting
 * @param {Array<Error|string>} errors - Array of errors
 * @returns {string[]} Formatted error messages
 */
function formatErrors(errors) {
  return errors.map((error) => {
    if (typeof error === "string") {
      return error;
    }
    if (error instanceof Error) {
      return `${error.name}: ${error.message}`;
    }
    if (error.message) {
      return error.message;
    }
    return String(error);
  });
}

export {
  buildLabelingReport,
  buildStandardizationReport,
  buildDryRunReport,
  formatErrors,
};
