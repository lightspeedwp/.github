async function analyzeContext(octokit, context) {
  const issue = context.payload.issue || context.payload.pull_request;
  if (!issue) {
    throw new Error("No issue or PR found in context");
  }

  const title = issue.title || "";
  const description = issue.body || "";
  const linkedIssues = extractLinkedIssues(description);

  let labels = [];
  try {
    const issueData = await octokit.rest.issues.get({
      owner: context.repo.owner,
      repo: context.repo.repo,
      issue_number: issue.number,
    });
    labels = issueData.data.labels.map((l) => l.name);
  } catch (error) {
    core.warning(`Could not fetch issue labels: ${error.message}`);
  }

  return {
    number: issue.number,
    title,
    description,
    labels,
    linkedIssues,
    type: determinePlanType(title, labels, description),
  };
}

function generatePlan(context) {
  switch (context.type) {
    case "architecture":
      return generateArchitecturePlan({ number: context.number });
    case "implementation":
      return generateImplementationPlan({ number: context.number });
    default:
      return generateTaskPlan({ number: context.number });
  }
}

async function run(context = github.context, options = {}) {
  const startTime = Date.now();
  try {
    const token = core.getInput("github-token") || process.env.GITHUB_TOKEN;
    if (!token) {
      throw new Error(
        "Missing GITHUB_TOKEN: provide via 'github-token' input or GITHUB_TOKEN env var",
      );
    }

    logger.info("Planner agent started", {
      event: "start",
      issueNumber:
        context.payload.issue?.number || context.payload.pull_request?.number,
      repo: context.repo.repo,
    });

    const dryRun =
      options.dryRun !== undefined
        ? options.dryRun
        : process.argv.includes("--dry-run") || process.env.DRY_RUN === "true";

    let octokit;
    try {
      octokit = github.getOctokit(token);
    } catch (error) {
      throw new Error(`Failed to initialize GitHub client: ${error.message}`);
    }

    const issue = context.payload.issue || context.payload.pull_request;
    if (!issue) {
      core.info("No PR or issue in context; exiting.");
      return;
    }

    const analysisContext = await analyzeContext(octokit, context);
    const plan = generatePlan(analysisContext);

    logger.info("Plan generated", {
      event: "plan-generated",
      planType: analysisContext.type,
      issueNumber: analysisContext.number,
    });

    if (dryRun) {
      core.info(`DRY-RUN: Would post plan:\n${plan}`);
      logger.info("Dry-run mode: plan not posted", { event: "dry-run" });
    } else {
      try {
        const prComments = await octokit.rest.issues.listComments({
          owner: context.repo.owner,
          repo: context.repo.repo,
          issue_number: issue.number,
        });

        const existingComment = prComments.data.find((c) =>
          c.body?.includes("<!-- planner-agent-summary -->"),
        );

        if (existingComment) {
          await octokit.rest.issues.updateComment({
            owner: context.repo.owner,
            repo: context.repo.repo,
            comment_id: existingComment.id,
            body: plan,
          });
          core.info("Planner comment updated.");
          logger.info("Comment updated successfully", {
            event: "comment-updated",
            issueNumber: issue.number,
            commentId: existingComment.id,
          });
        } else {
          await octokit.rest.issues.createComment({
            owner: context.repo.owner,
            repo: context.repo.repo,
            issue_number: issue.number,
            body: plan,
          });
          core.info("Planner comment posted.");
          logger.info("Comment posted successfully", {
            event: "comment-created",
            issueNumber: issue.number,
          });
        }
      } catch (error) {
        throw new Error(
          `Failed to post plan on #${issue.number}: ${error.message}`,
        );
      }
    }
    logger.info("Planner agent completed successfully", {
      event: "complete",
      duration: Date.now() - startTime,
    });
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    logger.error("Planner agent failed", {
      event: "error",
      error: message,
      duration: Date.now() - startTime,
    });
    core.setFailed(message);
    process.exit(1);
  }
}

async function runPlanner(options = {}) {
  const { dryRun = true } = options;

  try {
    const token = process.env.GITHUB_TOKEN;
    if (!token && !dryRun) {
      throw new Error(
        "Missing GITHUB_TOKEN environment variable (required for write operations)",
      );
    }

    const eventName = process.env.GITHUB_EVENT_NAME || "local";
    const repoRoot = path.resolve(__dirname, "..", "..");

    log(`Starting planner agent (${dryRun ? "dry-run" : "apply"})`);
    log(`Context: event=${eventName}, repoRoot=${repoRoot}`);

    if (!dryRun) {
      log("Planner stub mode: implement custom automation as needed.");
    }

    log("Planner agent finished without errors.");
  } catch (error) {
    console.error(`[planner] fatal error: ${error.message}`);
    process.exit(1);
  }
}

export { run, runPlanner };

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const dryRun = !process.argv.includes("--apply");
  run(github.context, { dryRun }).catch((error) => {
    console.error("[planner] fatal error", error);
    process.exit(1);
  });
}
