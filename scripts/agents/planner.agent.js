/**
 * planner.agent.js
 *
 * Generates and posts execution plans for PRs and issues.
 * Analyzes context (title, description, labels, linked issues) and generates
 * structured checklists for different plan types (architecture, implementation, task).
 * @module scripts/agents/planner.agent.js
 * @see agents/task-planner.agent.md
 */

import path from "path";
import { fileURLToPath, pathToFileURL } from "url";
import * as core from "@actions/core";
import * as github from "@actions/github";
import { Logger } from "../utils/logger.js";

const logger = new Logger(process.env.LOG_LEVEL || "info");

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

function log(message) {
  const timestamp = new Date().toISOString();
  console.log(`[planner] ${timestamp} ${message}`);
}

function extractLinkedIssues(text) {
  if (!text) return [];
  const issuePattern = /#(\d+)/g;
  const matches = text.match(issuePattern) || [];
  return matches.map((m) => m.slice(1));
}

function determinePlanType(title, labels, description) {
  const text = `${title} ${description || ""}`.toLowerCase();
  if (
    labels.includes("type:architecture") ||
    text.includes("design") ||
    text.includes("architecture")
  ) {
    return "architecture";
  }
  if (
    labels.includes("type:feature") ||
    labels.includes("type:enhancement") ||
    text.includes("implement")
  ) {
    return "implementation";
  }
  return "task";
}

