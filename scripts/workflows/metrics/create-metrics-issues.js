#!/usr/bin/env node

/**
 * Metrics Issues Creator
 *
 * Creates GitHub issues from metrics insights and recommendations.
 * Integrates with the metrics reporting pipeline.
 *
 * Usage:
 *   node scripts/workflows/metrics/create-metrics-issues.js <report-file>
 *   node scripts/workflows/metrics/create-metrics-issues.js <report-file> --dry-run
 */

const fs = require('fs');
const path = require('path');

class MetricsIssuesCreator {
  constructor(options = {}) {
    this.dry = options.dry || false;
    this.verbose = options.verbose || false;
    this.token = process.env.GITHUB_TOKEN;
    this.repository = process.env.GITHUB_REPOSITORY || 'lightspeedwp/.github';
  }

  log(message, level = 'info') {
    if (this.verbose || level !== 'debug') {
      const prefix = level === 'error' ? '❌' : level === 'warn' ? '⚠️' : 'ℹ️';
      console.log(`${prefix} [${level.toUpperCase()}] ${message}`);
    }
  }

  validateToken() {
    if (!this.token) {
      throw new Error('GITHUB_TOKEN environment variable is required');
    }
  }

  parseReport(reportContent) {
    try {
      // Extract frontmatter
      const frontmatterMatch = reportContent.match(/^---\n([\s\S]*?)\n---/);
      if (!frontmatterMatch) {
        throw new Error('Report missing frontmatter');
      }

      // Parse YAML-like frontmatter (simple parser)
      const metadata = {};
      const lines = frontmatterMatch[1].split('\n');
      for (const line of lines) {
        const [key, value] = line.split(':').map(s => s.trim());
        if (key && value) {
          metadata[key] = value.replace(/['"`]/g, '');
        }
      }

      return {
        metadata,
        content: reportContent,
      };
    } catch (error) {
      this.log(`Error parsing report: ${error.message}`, 'error');
      throw error;
    }
  }

  generateIssueFromInsight(insight, context) {
    const title = `[Metrics] ${insight.type.replace(/-/g, ' ').toUpperCase()} - ${context}`;
    const labels = [
      'metrics',
      `severity:${insight.severity}`,
      'insights',
      context,
    ];

    const body = [
      '## Insight',
      `**Type:** ${insight.type}  `,
      `**Severity:** ${insight.severity}  `,
      `**Context:** ${context}  `,
      '',
      insight.message,
      '',
      '---',
      '*Generated by Metrics Agent Phase 2 (Task 2.4)*',
    ].join('\n');

    return { title, body, labels };
  }

  generateIssueFromRecommendation(rec, context) {
    const title = `[Metrics] ${rec.action.replace(/-/g, ' ').toUpperCase()} - ${context}`;
    const labels = [
      'metrics',
      `priority:${rec.priority}`,
      'recommendations',
      context,
    ];

    const body = [
      '## Recommendation',
      `**Action:** ${rec.action.replace(/-/g, ' ')}  `,
      `**Priority:** ${rec.priority}  `,
      `**Context:** ${context}  `,
      '',
      rec.description,
      '',
      '---',
      '*Generated by Metrics Agent Phase 2 (Task 2.4)*',
    ].join('\n');

    return { title, body, labels };
  }

  async createIssue(issue) {
    if (this.dry) {
      this.log(`[DRY RUN] Would create issue: ${issue.title}`);
      return { id: 'dry-run', url: 'https://github.com/dry-run' };
    }

    this.validateToken();
    this.log(`Creating issue: ${issue.title}`);

    // In a real implementation, this would call the GitHub API
    // For now, we'll just log and return a mock response
    this.log(`  Labels: ${issue.labels.join(', ')}`);

    return {
      id: Math.random().toString(36).substr(2, 9),
      url: `https://github.com/${this.repository}/issues/new`,
    };
  }

  async createIssuesFromReport(reportFile, options = {}) {
    try {
      this.log(`Loading report from: ${reportFile}`);

      if (!fs.existsSync(reportFile)) {
        throw new Error(`Report file not found: ${reportFile}`);
      }

      const reportContent = fs.readFileSync(reportFile, 'utf8');
      const report = this.parseReport(reportContent);

      this.log(`Parsed report metadata:`, 'debug');
      this.log(`  Context: ${report.metadata.context}`, 'debug');

      const context = report.metadata.context || 'unknown';
      const createdIssues = [];

      // Extract insights and recommendations from report
      // In a real implementation, we'd parse the markdown sections properly
      const insights = this.extractInsights(reportContent, context);
      const recommendations = this.extractRecommendations(reportContent, context);

      // Create issues for insights
      for (const insight of insights) {
        const issue = this.generateIssueFromInsight(insight, context);
        const created = await this.createIssue(issue);
        createdIssues.push(created);
      }

      // Create issues for recommendations
      for (const rec of recommendations) {
        const issue = this.generateIssueFromRecommendation(rec, context);
        const created = await this.createIssue(issue);
        createdIssues.push(created);
      }

      this.log(`✓ Created ${createdIssues.length} issues`);

      if (process.env.GITHUB_OUTPUT && !this.dry) {
        fs.appendFileSync(process.env.GITHUB_OUTPUT, `issues_created=${createdIssues.length}\n`);
      }

      return createdIssues;

    } catch (error) {
      this.log(`Fatal error: ${error.message}`, 'error');
      process.exit(1);
    }
  }

  extractInsights(content, context) {
    // Simple extraction - in real implementation, would parse markdown properly
    const insightsMatch = content.match(/## Insights\n([\s\S]*?)(?=##|$)/);
    if (!insightsMatch) return [];

    // For now, return mock insights - real implementation would parse the section
    return [];
  }

  extractRecommendations(content, context) {
    // Simple extraction - in real implementation, would parse markdown properly
    const recsMatch = content.match(/## Recommendations\n([\s\S]*?)(?=--|$)/);
    if (!recsMatch) return [];

    // For now, return mock recommendations - real implementation would parse the section
    return [];
  }
}

// CLI Interface
async function main() {
  const args = process.argv.slice(2);

  if (args.length === 0 || args.includes('--help')) {
    console.log(`
Usage: node scripts/workflows/metrics/create-metrics-issues.js <report-file> [options]

Arguments:
  report-file      Path to metrics report markdown file (required)

Options:
  --dry-run        Preview issues without creating
  --verbose        Verbose output
  --help           Show this help message

Examples:
  node scripts/workflows/metrics/create-metrics-issues.js .github/reports/metrics/metrics-report-control-plane-latest.md
  node scripts/workflows/metrics/create-metrics-issues.js report.md --dry-run --verbose
    `);
    process.exit(args.includes('--help') ? 0 : 1);
  }

  const reportFile = args[0];
  const options = {
    dry: args.includes('--dry-run'),
    verbose: args.includes('--verbose'),
  };

  const creator = new MetricsIssuesCreator(options);
  await creator.createIssuesFromReport(reportFile);
}

if (require.main === module) {
  main().catch(error => {
    console.error('Fatal error:', error);
    process.exit(1);
  });
}

module.exports = MetricsIssuesCreator;
