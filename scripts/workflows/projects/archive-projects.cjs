#!/usr/bin/env node

/**
 * Archive completed projects
 *
 * Moves completed projects from active to archived folder,
 * creates archival summary with metrics, and generates report.
 */

const fs = require('fs');
const path = require('path');

const ACTIVE_DIR = process.env.ACTIVE_PROJECTS_DIR || '.github/projects/active';
const ARCHIVED_DIR = process.env.ARCHIVED_PROJECTS_DIR || '.github/projects/archived';
const DRY_RUN = process.env.DRY_RUN === 'true';
const PROJECTS_JSON = process.env.PROJECTS_JSON || '[]';

const reportDir = '.github/reports/projects';

try {
  // Ensure report directory exists
  if (!fs.existsSync(reportDir)) {
    fs.mkdirSync(reportDir, { recursive: true });
  }

  let projects = [];
  try {
    projects = JSON.parse(PROJECTS_JSON);
  } catch (err) {
    console.error('❌ Invalid projects JSON:', err.message);
    process.exit(1);
  }

  if (!Array.isArray(projects) || projects.length === 0) {
    console.log('ℹ️  No projects to archive');
    process.exit(0);
  }

  const timestamp = new Date().toISOString().split('T')[0];
  const report = [];
  report.push(`# Project Archival Report\n`);
  report.push(`**Date:** ${new Date().toISOString()}`);
  report.push(`**Mode:** ${DRY_RUN ? 'Dry-run' : 'Live'}\n`);
  report.push(`## Summary\n`);
  report.push(`Total projects archived: **${projects.length}**\n`);
  report.push(`## Archived Projects\n`);

  const summary = [];
  let successCount = 0;

  for (const project of projects) {
    const { name, path: projectPath, archivedAt } = project;

    if (!fs.existsSync(projectPath)) {
      console.log(`⚠️  Project path not found: ${projectPath}`);
      report.push(`- ❌ **${name}** — path not found\n`);
      continue;
    }

    const archivedPath = path.join(ARCHIVED_DIR, `${archivedAt}-${name}`);

    try {
      if (!DRY_RUN) {
        // Ensure archived directory exists
        if (!fs.existsSync(ARCHIVED_DIR)) {
          fs.mkdirSync(ARCHIVED_DIR, { recursive: true });
        }

        // Move project to archived folder
        fs.renameSync(projectPath, archivedPath);

        // Create archival summary file
        const summaryFile = path.join(archivedPath, 'ARCHIVAL_SUMMARY.md');
        const archivedSummary = generateArchivedSummary(name, archivedAt);
        fs.writeFileSync(summaryFile, archivedSummary, 'utf8');

        console.log(`✅ Archived project: ${name}`);
        report.push(`- ✅ **${name}** — moved to \`.github/projects/archived/${path.basename(archivedPath)}/\`\n`);
        successCount++;
      } else {
        console.log(`🔍 [DRY-RUN] Would archive: ${name}`);
        report.push(`- 🔍 **${name}** — would be archived (dry-run mode)\n`);
      }

      summary.push(`  - ${name}`);
    } catch (err) {
      console.error(`❌ Error archiving ${name}: ${err.message}`);
      report.push(`- ❌ **${name}** — error: ${err.message}\n`);
    }
  }

  // Write report file
  const reportFile = path.join(reportDir, `archival-report-${Date.now()}.md`);
  fs.writeFileSync(reportFile, report.join('\n'), 'utf8');

  // Write summary file for workflow output
  const summaryFile = path.join(reportDir, 'archival-summary.txt');
  const summaryText = `
📦 Project Archival Complete
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Mode: ${DRY_RUN ? 'Dry-run' : 'Live'}
Projects archived: ${successCount}/${projects.length}

${summary.length > 0 ? summary.join('\n') : '(no projects archived)'}

Report: ${reportFile}
`;
  fs.writeFileSync(summaryFile, summaryText.trim(), 'utf8');

  console.log(`\n✅ Archival complete. Report: ${reportFile}`);
  process.exit(0);
} catch (err) {
  console.error(`❌ Error during archival: ${err.message}`);
  process.exit(1);
}

/**
 * Generate archival summary content for archived project
 */
function generateArchivedSummary(projectName, archivedDate) {
  return `# Archival Summary

**Project:** ${projectName}
**Archived:** ${archivedDate}
**Archived At:** ${new Date().toISOString()}

## Overview

This project was archived after completion. Original materials are preserved in this directory.

## Contents

- Original project files and documentation
- All associated issues and pull requests (closed)
- Planning documents and execution records

## Future Reference

To restore this project to active status:
1. Move this directory back to \`.github/projects/active/${projectName}/\`
2. Update the project status in PARENT_ISSUE.md
3. Create a GitHub issue to track restoration

---

*This summary was automatically generated by the project-archival workflow.*
`;
}
