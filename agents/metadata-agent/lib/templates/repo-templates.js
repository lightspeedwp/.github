/**
 * Repository-aware report templates for Reporting Agent v2.
 * Each template is keyed by RepoType and returns a structured Markdown scaffold.
 */

/**
 * @typedef {Object} TemplateContext
 * @property {string} repoName - Repository name
 * @property {string} owner - Repository owner
 * @property {string} date - ISO date string (YYYY-MM-DD)
 * @property {string} [description] - Repository description
 * @property {string} [period] - Reporting period label (e.g. "2026-08")
 */

/**
 * Generate the YAML frontmatter block for a report.
 *
 * @param {string} title
 * @param {string} description
 * @param {string} category
 * @param {string} date
 * @param {string} repoName
 * @returns {string}
 */
function buildFrontmatter(title, description, category, date, repoName) {
  return [
    "---",
    `title: "${title}"`,
    `description: "${description}"`,
    `file_type: report`,
    `category: ${category}`,
    `created_date: "${date}"`,
    `version: "v1.0.0"`,
    `repository: "${repoName}"`,
    `authors: ["automation"]`,
    `tags: ["${category}", "automated-report", "${repoName}"]`,
    "---",
    "",
  ].join("\n");
}

