/** @type {Record<string, (ctx: TemplateContext) => string>} */
const TEMPLATES = {
  "block-plugin": blockPluginTemplate,
  "block-theme": blockThemeTemplate,
  "control-plane": controlPlaneTemplate,
  platform: platformTemplate,
  unknown: unknownTemplate,
};

/**
 * Render a repository-aware report using the appropriate template.
 *
 * @param {string} templateKey - One of the RepoType values
 * @param {TemplateContext} ctx - Template context data
 * @returns {string} Rendered Markdown report
 */
function renderTemplate(templateKey, ctx) {
  const fn = TEMPLATES[templateKey] || unknownTemplate;
  return fn(ctx);
}

module.exports = {
  TEMPLATES,
  renderTemplate,
  blockPluginTemplate,
  blockThemeTemplate,
  controlPlaneTemplate,
  platformTemplate,
  unknownTemplate,
  buildFrontmatter,
};
